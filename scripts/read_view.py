#!/usr/bin/env python3
"""Reading view of a raw run log: one entry per model call with its prompt, reasoning, answer, parsed verdict and
receipt, each linked to the raw-log line it came from. A view only - the raw log stays the ground truth.

  python3 scripts/read_view.py <out.md> <log>[@A,B,...] [<log>[@F,G] ...]

`@cases` keeps only calls whose label starts with one of those case letters (to pool one result's cases across logs);
GATE and other labels are kept only when no filter is given for that log. Reasoning billed but not returned shows
as MISSING, so a gap is visible."""
import os
import re
import sys

SEP = "=" * 78


def entries(path):
    lines = open(path).read().split("\n")
    i = 0
    while i < len(lines):
        m = re.match(r"\[([^\]]+)\]\s+model=(\S+)\s+request_id=(\S+)", lines[i])
        if not m:
            i += 1
            continue
        e = {"label": m[1], "model": m[2], "rid": m[3], "line": i + 1, "prompt": [], "thinking": [], "answer": [],
             "verdict": "", "flags": []}
        sec, j = None, i + 1
        while j < len(lines) and lines[j] != SEP and not re.match(r"\[[^\]]+\]\s+model=", lines[j]):
            s = lines[j]
            if s.startswith("--- PROMPT"):
                sec = "prompt"
            elif s.startswith("--- THINKING"):
                sec = "thinking"
            elif s.startswith("--- RESPONSE"):
                sec = "answer"
            elif s.startswith("--- PARSED VERDICT"):
                e["verdict"], sec = s[len("--- PARSED VERDICT: "):].rstrip(" -"), None
            elif s.startswith("### "):
                sec = None
            elif s.lstrip().startswith("!!!"):
                e["flags"].append(s.strip())
            elif sec:
                e[sec].append(s)
            j += 1
        yield e
        i = j


def block(title, text, open_=False):
    body = "\n".join(text).strip()
    return f"<details{' open' if open_ else ''}><summary>{title}</summary>\n\n```text\n{body}\n```\n\n</details>\n"


def main():
    out, specs = sys.argv[1], sys.argv[2:]
    if not specs:
        sys.exit(__doc__)
    rel = lambda p: os.path.relpath(p, os.path.dirname(os.path.abspath(out)))
    parts = [f"# Reading view: {', '.join(os.path.basename(s) for s in specs)}\n",
             "Generated by `scripts/read_view.py` from the raw logs below. Every heading links to the raw-log line; "
             "the raw log is the ground truth, this is only a view.\n"]
    n = missing = 0
    for spec in specs:
        path, _, cases = spec.partition("@")
        keep = set(cases.split(",")) if cases else None
        parts.append(f"\n## Log `{path}`" + (f" (cases {cases})" if cases else "") + "\n")
        for e in entries(path):
            if keep is not None and e["label"].split("/")[0] not in keep:
                continue
            n += 1
            gap = any("THINKING MISSING" in f for f in e["flags"])
            missing += gap
            link = f"{rel(path)}#L{e['line']}"
            parts.append(f"\n### {e['label']}  -  [`{os.path.basename(path)}:{e['line']}`]({link})\n\n"
                         f"model `{e['model']}` - receipt `{e['rid']}`\n\n")
            parts.append(f"**Verdict:** `{e['verdict']}`\n\n" if e["verdict"] else "")
            parts += [f"**{f}**\n\n" for f in e["flags"]]
            parts.append(block("Prompt sent", e["prompt"]) if e["prompt"] else "_(prompt: continues the turn above)_\n\n")
            if e["thinking"]:
                parts.append(block("Reasoning (as returned)", e["thinking"]))
            elif gap:
                parts.append("_Reasoning: MISSING (billed, not returned)_\n\n")
            parts.append(block("Answer (visible)", e["answer"], open_=True))
    parts.insert(2, f"\n{n} calls; reasoning missing on {missing}.\n")
    open(out, "w").write("".join(parts))
    print(f"{out}: {n} calls, reasoning missing on {missing}")


if __name__ == "__main__":
    main()
